"""Work Plan Phase 3: train the predictors on the OMNeT++ windows.

Reads the feature rows written by AdaptivePlcaController, labels each with the
state of the next 20 ms by the rule in plca_sim/tinyml.py, trains on the first
two seeds of every load and tests on the third.

    python -m ml.run_omnet_tinyml --windows results/omnet/windows

Outputs in results/omnet/:
    tinyml_dataset.csv.gz      labelled windows, the dataset the plan releases
    model_comparison.csv       accuracy and F1 per class on the unseen seed
    plca_state_model.h         decision tree as C
    plca_state_model_mlp.h     int8 MLP as C
"""

from __future__ import annotations

import argparse
import re
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler

from plca_sim.monitor import FEATURES
from plca_sim.tinyml import TrainedModel, export_c, state_of, train_tree
from ml.run_models import quantized_predict, row, timed

LOADS = {"S2": (0.25, 0.3, 0.5, 0.7, 0.9), "S3": (0.3, 0.5, 0.7, 0.9), "S4": (0.3, 0.5, 0.7, 0.9)}
HORIZON = 4
SEEDS_PER_LOAD = 3
TEST_SEED = 2


def load_run(path: Path) -> pd.DataFrame:
    scenario, run = re.fullmatch(r"Dataset_(S\d)-(\d+)\.csv", path.name).groups()
    df = pd.read_csv(path, header=None, names=["time_s", *FEATURES])
    h = HORIZON
    future_util = df.util[::-1].rolling(h).mean()[::-1].shift(-1)
    future_queue = df.queue_total[::-1].rolling(h).max()[::-1].shift(-1)
    df["state_now"] = state_of(df.util.rolling(h, min_periods=1).mean(),
                               df.queue_total.rolling(h, min_periods=1).max())
    keep = future_util.notna()
    df = df[keep].copy()
    df["state_next"] = state_of(future_util[keep], future_queue[keep])
    # Repetition is the innermost iteration, so run numbers go load by load.
    df["scenario"] = scenario
    df["load"] = LOADS[scenario][int(run) // SEEDS_PER_LOAD]
    df["seed"] = int(run) % SEEDS_PER_LOAD
    return df


def mlp_header(mlp: MLPClassifier, scale: StandardScaler) -> str:
    """Int8 weights with one scale per layer, as quantized_predict rounds them."""
    lines = ["/* Auto-generated by run_omnet_tinyml.py - do not edit. */",
             "#ifndef PLCA_STATE_MODEL_MLP_H", "#define PLCA_STATE_MODEL_MLP_H", "", "#include <stdint.h>", ""]
    layers = []
    for i, (w, b) in enumerate(zip(mlp.coefs_, mlp.intercepts_)):
        s = float(max(np.abs(w).max(), np.abs(b).max()) / 127)
        layers.append((w.shape[0], w.shape[1], s))
        wq = np.round(w / s).astype(int).ravel()
        bq = np.round(b / s).astype(int)
        lines.append(f"static const int8_t plca_w{i}[{wq.size}] = {{{','.join(map(str, wq))}}};")
        lines.append(f"static const int8_t plca_b{i}[{bq.size}] = {{{','.join(map(str, bq))}}};")
    n = scale.mean_.size
    lines.append(f"static const float plca_mean[{n}] = {{{','.join(f'{v:.6g}f' for v in scale.mean_)}}};")
    lines.append(f"static const float plca_inv[{n}] = {{{','.join(f'{1 / v:.6g}f' for v in scale.scale_)}}};")
    lines += ["", f"static inline int plca_predict_mlp(const float f[{n}])", "{",
              f"    float a[{n}], next[16];", f"    int width = {n};",
              f"    for (int i = 0; i < {n}; i++)", "        a[i] = (f[i] - plca_mean[i]) * plca_inv[i];"]
    for i, (rows, cols, s) in enumerate(layers):
        relu = i < len(layers) - 1
        lines += [f"    for (int c = 0; c < {cols}; c++) {{", "        float v = 0;",
                  f"        for (int r = 0; r < width; r++) v += a[r] * plca_w{i}[r * {cols} + c];",
                  f"        v = (v + plca_b{i}[c]) * {s:.8g}f;",
                  f"        next[c] = {'v > 0 ? v : 0' if relu else 'v'};", "    }",
                  f"    width = {cols};", f"    for (int c = 0; c < {cols}; c++) a[c] = next[c];"]
    lines += ["    int best = 0;", "    for (int c = 1; c < width; c++)", "        if (a[c] > a[best]) best = c;",
              "    return best;", "}", "", "#endif", ""]
    return "\n".join(lines)


def report(df: pd.DataFrame, out: Path) -> pd.DataFrame:
    cols = list(FEATURES)
    train, test = df[df.seed != TEST_SEED], df[df.seed == TEST_SEED]
    x_tr, x_te = train[cols].to_numpy(), test[cols].to_numpy()
    y_tr, y = train.state_next.to_numpy(), test.state_next.to_numpy()
    rows = []

    tree = train_tree(train)
    pred, us = timed(tree.tree.predict, x_te)
    rows.append(row("decision tree, depth 4", y, pred, tree.n_nodes * 8, us))
    (out / "plca_state_model.h").write_text(export_c(tree))

    forest = RandomForestClassifier(n_estimators=20, max_depth=6, class_weight="balanced",
                                    random_state=0, n_jobs=4).fit(x_tr, y_tr)
    pred, us = timed(forest.predict, x_te)
    rows.append(row("random forest, 20 trees", y, pred, sum(t.tree_.node_count for t in forest.estimators_) * 8, us))

    scale = StandardScaler().fit(x_tr)
    mlp = MLPClassifier((16, 16), max_iter=300, random_state=0).fit(scale.transform(x_tr), y_tr)
    weights = sum(w.size for w in mlp.coefs_) + sum(b.size for b in mlp.intercepts_)
    z = scale.transform(x_te)
    pred, us = timed(mlp.predict, z)
    rows.append(row("MLP 2x16, float32", y, pred, weights * 4, us))
    pred, us = timed(lambda v: quantized_predict(mlp, v), z)
    rows.append(row("MLP 2x16, int8", y, pred, weights, us))
    (out / "plca_state_model_mlp.h").write_text(mlp_header(mlp, scale))

    boost = HistGradientBoostingClassifier(max_iter=300, class_weight="balanced", random_state=0).fit(x_tr, y_tr)
    rows.append(row("gradient boosting (reference)", y, boost.predict(x_te), 0))

    rows.append(row("EWMA threshold, no ML", y, state_of(test.util_ewma, test.queue_total), 0))
    rows.append(row("persistence, no ML", y, test.state_now.to_numpy(), 0))
    best = train.groupby(["scenario", "load"]).state_next.agg(lambda s: s.mode().iloc[0]).rename("oracle")
    rows.append(row("oracle (true scenario and load)", y, test.join(best, on=["scenario", "load"]).oracle.to_numpy(), 0))

    table = pd.DataFrame(rows)
    table.to_csv(out / "model_comparison.csv", index=False)
    return table


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--windows", type=Path, default=Path("results/omnet/windows"))
    ap.add_argument("--out", type=Path, default=Path("results/omnet"))
    args = ap.parse_args()
    t0 = time.time()
    df = pd.concat([load_run(p) for p in sorted(args.windows.glob("Dataset_S*-*.csv"))], ignore_index=True)
    df.to_csv(args.out / "tinyml_dataset.csv.gz", index=False)
    print(len(df), "windows;", df.state_next.value_counts(normalize=True).sort_index().round(3).to_dict())
    print(report(df, args.out).round(3).to_string(index=False))
    print(f"{time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
