"""TinyML network-state prediction (framework block 3).

Given the features of the current 5 ms monitoring window, predict the network
state over the next `horizon` windows (default 4 x 5 ms = 20 ms):
0 = low, 1 = medium, 2 = high, 3 = congested.

A single 5 ms window holds only ~10 frames, so its utilization is mostly
random; the state over the next ~20 ms is what an adaptive policy can act on.

The model is a small decision tree: it needs no floating-point library, runs
in a handful of comparisons and can be exported as plain C for an ECU.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

from .config import PLCAConfig
from .monitor import FEATURES, MonitoringPolicy
from .scenarios import make_traffic
from .simulator import simulate

STATES = ("low", "medium", "high", "congested")

# State thresholds on average bus utilization over the horizon.
UTIL_MEDIUM = 0.30
UTIL_HIGH = 0.60
UTIL_CONGESTED = 0.85
# ...or congested if this many frames are waiting at some point in the horizon.
QUEUE_CONGESTED = 10


def state_of(util: np.ndarray, queue_total: np.ndarray) -> np.ndarray:
    """Network state of a window from its utilization and end-of-window queue."""
    util = np.asarray(util)
    queue_total = np.asarray(queue_total)
    s = np.zeros(len(util), dtype=int)
    s[util >= UTIL_MEDIUM] = 1
    s[util >= UTIL_HIGH] = 2
    s[(util >= UTIL_CONGESTED) | (queue_total >= QUEUE_CONGESTED)] = 3
    return s


def collect_samples(
    scenario: str,
    load: float,
    seed: int,
    cfg: PLCAConfig,
    duration_s: float,
    window_s: float = 5e-3,
    horizon: int = 4,
) -> pd.DataFrame:
    """Simulate conventional PLCA and return labelled feature windows."""
    frames = make_traffic(scenario, load, cfg, duration_s, seed)
    df = monitor_windows(frames, cfg, duration_s, window_s, horizon)
    if df.empty:
        return df
    df["scenario"] = scenario
    df["load"] = load
    df["seed"] = seed
    return df


def monitor_windows(
    frames: list,
    cfg: PLCAConfig,
    duration_s: float,
    window_s: float = 5e-3,
    horizon: int = 4,
) -> pd.DataFrame:
    """Run `frames` on conventional PLCA and return labelled feature windows."""
    pol = MonitoringPolicy(cfg, window_s=window_s)
    simulate(frames, cfg, cfg.s_to_bt(duration_s), pol)
    df = pd.DataFrame(pol.monitor.samples)
    if len(df) < 2 * horizon:
        return pd.DataFrame()
    h = horizon
    # Label = state over the NEXT h windows (what the model must predict).
    fut_util = df.util[::-1].rolling(h).mean()[::-1].shift(-1)
    fut_queue = df.queue_total[::-1].rolling(h).max()[::-1].shift(-1)
    # Persistence baseline = same rule applied to the PAST h windows.
    past_util = df.util.rolling(h, min_periods=1).mean()
    past_queue = df.queue_total.rolling(h, min_periods=1).max()
    keep = fut_util.notna()
    df["state_now"] = state_of(past_util, past_queue)
    df = df[keep].copy()
    df["state_next"] = state_of(fut_util[keep], fut_queue[keep])
    return df


def build_dataset(
    scenarios: tuple[str, ...],
    loads: tuple[float, ...],
    seeds: tuple[int, ...],
    cfg: PLCAConfig,
    duration_s: float,
    window_s: float = 5e-3,
    horizon: int = 4,
    progress: bool = True,
) -> pd.DataFrame:
    parts = []
    for sc in scenarios:
        for load in loads:
            for seed in seeds:
                parts.append(collect_samples(sc, load, seed, cfg, duration_s, window_s, horizon))
        if progress:
            print(f"  collected {sc}")
    return pd.concat(parts, ignore_index=True)


@dataclass
class TrainedModel:
    tree: object  # sklearn DecisionTreeClassifier
    features: tuple[str, ...] = FEATURES

    def predict(self, feat: dict[str, float]) -> int:
        x = np.array([[feat[f] for f in self.features]])
        return int(self.tree.predict(x)[0])

    @property
    def n_nodes(self) -> int:
        return int(self.tree.tree_.node_count)

    @property
    def depth(self) -> int:
        return int(self.tree.get_depth())


def train_tree(df: pd.DataFrame, max_depth: int = 4, min_samples_leaf: int = 20) -> TrainedModel:
    from sklearn.tree import DecisionTreeClassifier

    tree = DecisionTreeClassifier(
        max_depth=max_depth,
        min_samples_leaf=min_samples_leaf,
        class_weight="balanced",
        random_state=0,
    )
    tree.fit(df[list(FEATURES)].to_numpy(), df["state_next"].to_numpy())
    return TrainedModel(tree)


def export_c(model: TrainedModel) -> str:
    """Export the tree as a dependency-free C function for an ECU."""
    t = model.tree.tree_
    lines = [
        "/* Auto-generated by plca_sim.tinyml.export_c - do not edit. */",
        "/* Predicts the PLCA network state over the next ~20 ms:",
        "   0 = low, 1 = medium, 2 = high, 3 = congested. */",
        "#ifndef PLCA_STATE_MODEL_H",
        "#define PLCA_STATE_MODEL_H",
        "",
    ]
    for i, f in enumerate(model.features):
        lines.append(f"#define PLCA_F_{f.upper()} {i}")
    lines += [f"#define PLCA_NUM_FEATURES {len(model.features)}", ""]
    lines.append("static inline int plca_predict_state(const float f[PLCA_NUM_FEATURES])")
    lines.append("{")

    classes = model.tree.classes_

    def emit(node: int, indent: int) -> None:
        pad = "    " * indent
        if t.children_left[node] == t.children_right[node]:  # leaf
            cls = int(classes[int(np.argmax(t.value[node][0]))])
            lines.append(f"{pad}return {cls}; /* {STATES[cls]} */")
            return
        feat = model.features[t.feature[node]]
        lines.append(f"{pad}if (f[PLCA_F_{feat.upper()}] <= {t.threshold[node]:.6g}f) {{")
        emit(t.children_left[node], indent + 1)
        lines.append(f"{pad}}} else {{")
        emit(t.children_right[node], indent + 1)
        lines.append(f"{pad}}}")

    emit(0, 1)
    lines += ["}", "", "#endif /* PLCA_STATE_MODEL_H */", ""]
    return "\n".join(lines)
